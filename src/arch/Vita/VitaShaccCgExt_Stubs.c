// Background: the vdpm-shipped libvitashark.a references
// sceShaccCgExtEnableExtensions / sceShaccCgExtDisableExtensions, but the
// VitaSDK snapshot in use has no SceShaccCgExt stub library (only
// SceShaccCg_stub). These entry points live in libshacccg.suprx on the
// console and only gate *extended* compiler intrinsics.
//
// Stage-1 rationale: StepMania-on-vitaGL uses the fixed-function pipeline
// with vitaGL's precompiled shaders, so no runtime GLSL compilation is
// expected. No-op stubs let us link; if runtime shader compilation ever
// needs the extensions, replace this file with a proper stub generated by
// vita-libs-gen from newer vita-headers (SceShaccCgExt).
