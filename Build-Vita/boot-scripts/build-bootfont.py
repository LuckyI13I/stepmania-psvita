"""Bake slkscr 16px ASCII glyphs for boot splash dynamic text.
Writes vpk/bootart/font16.raw (95 cells of 16x16 RGBA white w/alpha)
and stepmania-5.0.12/src/arch/Vita/vita_bootfont.h (advances).
(repo layout: src/arch/Vita/vita_bootfont.h)
Usage: python build-bootfont.py [workspace-root]
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[2]
TREE = ROOT / "stepmania-5.0.12" if (ROOT / "stepmania-5.0.12").is_dir() else ROOT
TTF = ROOT / "fonts" / "slkscr.ttf"
OUTDIR = ROOT / "vpk" / "bootart"
SRC = TREE / "src" / "arch" / "Vita"

CELL = 16
FIRST, LAST = 32, 126
font = ImageFont.truetype(str(TTF), 16)

cells = []
advs = []
for code in range(FIRST, LAST + 1):
    ch = chr(code)
    cell = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    d = ImageDraw.Draw(cell)
    try:
        l, t, r, b = font.getbbox(ch)
        w = max(r - l, 1)
    except Exception:
        w, l, t = 6, 0, 0
    d.text((2 - l, 2 - t), ch, font=font, fill=(255, 255, 255, 255))
    cells.append(cell.tobytes())
    advs.append(min(w + 3, CELL))

OUTDIR.mkdir(parents=True, exist_ok=True)
(OUTDIR / "font16.raw").write_bytes(b"".join(cells))
print("font16.raw", len(b"".join(cells)), "bytes")

hdr = []
hdr.append("// GENERATED by build-bootfont - do not edit.")
hdr.append("// slkscr 16px ASCII 32..126, 16x16 RGBA cells (white, alpha coverage).")
hdr.append("#ifndef VITA_BOOTFONT_H")
hdr.append("#define VITA_BOOTFONT_H")
hdr.append("")
hdr.append("static const int VITA_BOOTFONT_FIRST = 32;")
hdr.append("static const int VITA_BOOTFONT_LAST = 126;")
hdr.append("static const int VITA_BOOTFONT_CELL = 16;")
hdr.append("static const unsigned char VITA_BOOTFONT_ADV[95] = {")
for r in range(0, 95, 12):
    hdr.append("	" + ", ".join(str(a) for a in advs[r:r+12]) + ",")
hdr.append("};")
hdr.append("#endif")
(SRC / "vita_bootfont.h").write_text("\n".join(hdr) + "\n")
print("wrote vita_bootfont.h")
