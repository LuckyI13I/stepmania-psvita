"""One-off asset bake for the Vita boot splash.
Reads arts/LDSM4V.png + fonts/slkscr.ttf, writes:
  vpk/bootart/bg.raw            960x544 raw RGBA bytes
  vpk/bootart/stage_<i>.raw     pre-rendered stage labels (raw RGBA + alpha)
  stepmania-5.0.12/src/arch/Vita/vita_bootstages.h   generated manifest
  (repo layout: src/arch/Vita/vita_bootstages.h)
Usage: python build-bootart-assets.py [workspace-root]
"""
import pathlib
import sys

from PIL import Image, ImageFont, ImageDraw

ROOT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path(__file__).resolve().parents[2]
ART = ROOT / "arts" / "LDSM4V.png"
TTF = ROOT / "fonts" / "slkscr.ttf"
OUTDIR = ROOT / "vpk" / "bootart"
SRC = ROOT / "src" / "arch" / "Vita"

# (stage id, label) - ids must match VitaBootStage enum in VitaBootSplash.h
STAGES = [
    ("loading", "loading..."),
    ("extract", "extracting data..."),
    ("theme", "loading theme..."),
    ("sound", "loading sound..."),
    ("songs", "loading songs..."),
    ("courses", "loading courses..."),
    ("profiles", "loading profiles..."),
    ("display", "starting display..."),
    ("screens", "loading screens..."),
    ("menu", "starting menu..."),
    ("error", "error"),
]

FONT_PX = 32  # silkscreen is a pixel font; 32 = 4x crisp pixels

im = Image.open(ART).convert("RGBA")
assert im.size == (960, 544), im.size
OUTDIR.mkdir(parents=True, exist_ok=True)
(OUTDIR / "bg.raw").write_bytes(im.tobytes())
print("bg.raw", len(im.tobytes()), "bytes")

font = ImageFont.truetype(str(TTF), FONT_PX)

def text_size(s):
    l, t, r, b = font.getbbox(s)
    return r - l, b - t, l, t

entries = []
for i, (sid, label) in enumerate(STAGES):
    w, h, ox, oy = text_size(label)
    pad = 4
    W, H = w + pad * 2, h + pad * 2
    layer = Image.new("RGBA", (W, H), (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    # black shadow then white face
    d.text((pad - ox + 2, pad - oy + 2), label, font=font, fill=(0, 0, 0, 255))
    d.text((pad - ox, pad - oy), label, font=font, fill=(255, 255, 255, 255))
    fn = f"stage_{i:02d}.raw"
    (OUTDIR / fn).write_bytes(layer.tobytes())
    entries.append((sid, fn, W, H))
    print(fn, f"{W}x{H}", repr(label))

hdr = []
hdr.append("// GENERATED by build-bootart-assets.py - do not edit.")
hdr.append("// Pre-rendered boot stage labels (raw RGBA sprites).")
hdr.append("#ifndef VITA_BOOTSTAGES_H")
hdr.append("#define VITA_BOOTSTAGES_H")
hdr.append("")
hdr.append("struct VitaBootStageArt { const char *id; const char *file; int w; int h; };")
hdr.append("")
hdr.append("static const VitaBootStageArt VITA_BOOT_STAGE_ARTS[] = {")
for sid, fn, w, h in entries:
    hdr.append(f'	{{ "{sid}", "app0:bootart/{fn}", {w}, {h} }},')
hdr.append("};")
hdr.append("")
hdr.append(f"static const int VITA_BOOT_STAGE_COUNT = {len(entries)};")
hdr.append("#endif")
(SRC / "vita_bootstages.h").write_text("\n".join(hdr) + "\n")
print("wrote vita_bootstages.h with", len(entries), "stages")
